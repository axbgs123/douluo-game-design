function inferTrigger(name: string, hint: string, index: number): GoldFingerTrigger {
  const text = `${name}${hint}`;
  if (/签到|每日|膳食|节令|岁序/.test(text)) return "每日";
  if (/地标|地点|迷雾地图|归巢/.test(text)) return "新地点";
  if (/训练|熟练|加点|修炼|技能树|协调|影子陪练/.test(text)) return "训练后";
  if (/失败|败因|残材|霉运/.test(text)) return "失败后";
  if (/伤势|濒危|绝境/.test(text)) return "受伤时";
  if (/睡眠|深眠|疲劳|情绪/.test(text)) return "疲劳时";
  if (/任务|委托|订单|计划|挑战|救援/.test(text)) return "任务中";
  if (/战斗|魂技|敌手|阵型|抗性|破绽|魂力预算|节奏/.test(text)) return "战斗中";
  if (/交易|拍卖|经营|交换|行情/.test(text)) return "交易时";
  if (/制作|锻造|药性|炉温|蓝图|修复/.test(text)) return "制作时";
  if (/旅行|行路|迁徙|家书/.test(text)) return "旅行时";
  if (/关系|羁绊|导师|誓言|宿敌|人情|谈判/.test(text)) return "关系中";
  if (/魂环/.test(text)) return "魂环前";
  if (/夜|梦境/.test(text)) return "夜间";
  if (/物品|器物|行囊|样本|遗物/.test(text)) return "持有物品";
  if (/势力|阵营|声望/.test(text)) return "加入势力";
  if (/选择|因果|命运|机缘|预言|时间线|异常/.test(text)) return "重大选择";
  if (/图鉴|生态|药草|矿脉|足迹|毒性|风云/.test(text)) return "新样本";
  if (/调查|解析|回溯|校验|谱系|解码|记忆/.test(text)) return "调查时";
  return triggerCycle[index % triggerCycle.length];
}

function inferCost(name: string, hint: string, index: number): GoldFingerCost {
  const text = `${name}${hint}`;
  if (/实验|制作|锻造|修复|取样|药性|回收|样本/.test(text)) return "材料";
  if (/模拟|推演|预演|思维|记忆|梦境|译文|编译|回放/.test(text)) return "疲劳";
  if (/交易|拍卖|经营|家书|预支/.test(text)) return "魂币";
  if (/极限|伤势|守夜|抗性|绝境/.test(text)) return "体力";
  return costCycle[Math.floor(index / 2) % costCycle.length];
}

function inferReward(name: string, hint: string, index: number): GoldFingerReward {
  const text = `${name}${hint}`;
  if (/加点|熟练|训练|修炼|技能|协调|极限/.test(text)) return "潜能";
  if (/调查|解析|校验|回溯|证词|谱系|译文|记忆|书阁/.test(text)) return "情报";
  if (/地标|地图|迁徙|探索|生态|药草|矿脉|足迹|样本/.test(text)) return "发现";
  if (/伤势|睡眠|膳食|情绪|恢复/.test(text)) return "恢复";
  if (/经营|订单|回收|签到/.test(text)) return "魂币";
  if (/关系|导师|誓言|羁绊|声望|阵营|人情/.test(text)) return "声望";
  if (/制作|锻造|药性|遗物|行囊|蓝图/.test(text)) return "物品";
  if (/战斗|魂技|魂环|武魂|阵型|敌手|抗性/.test(text)) return "训练效率";
  if (/风险|命运|选择|因果|危机|预言|异常|保险/.test(text)) return "风险标记";
  return rewardCycle[(index * 3 + Math.floor(index / 10)) % rewardCycle.length];
}

const specialPreferences: Record<string, string> = {
  "万象签到系统": "签到系统", "勤修加点面板": "加点面板", "命运片段模拟器": "人生模拟器", "等价任务系统": "任务系统", "武魂生态图鉴": "图鉴系统",
};

let serial = 0;
function group(category: string, seeds: readonly Seed[]): GoldFingerDefinition[] {
  return seeds.map(([name, hint, actionCommand, constraint]) => {
    const index = serial++;
    const trigger = inferTrigger(name, hint, index);
    const cost = inferCost(name, hint, index);
    const reward = inferReward(name, hint, index);
    const cooldownDays = [0, 1, 3, 7, 14][index % 5];
    return {
      id: `gold-finger-${String(index + 1).padStart(3, "0")}`,
      name, category, preference: specialPreferences[name] ?? name, hint,
      resourceHint: `${trigger}触发；${cost === "无" ? "不消耗资源" : `消耗${cost}`}；主要反馈为${reward}。限制：${constraint}`,
      initialAbilities: [`${trigger}触发`, `${reward}反馈`],
      actionLabel: name === "万象签到系统" ? "今日签到" : actionCommand.replace(/^(查看|进行|启动|开启|尝试|记录|使用)/, ""),
      actionCommand,
      mechanic: { trigger, cost, reward, cooldownDays, constraint },
    };
  });
}

