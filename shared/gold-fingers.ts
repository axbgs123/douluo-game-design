export function goldFingerByPreference(preference: string): GoldFingerDefinition | undefined {
  return GOLD_FINGERS.find((item) => item.preference === preference || item.name === preference);
}

export function goldFingerByName(name: string): GoldFingerDefinition | undefined {
  return GOLD_FINGERS.find((item) => item.name === name);
}

export function goldFingerMechanicSignature(item: GoldFingerDefinition): string {
  const mechanic = item.mechanic;
  return [mechanic.trigger, mechanic.cost, mechanic.reward, mechanic.cooldownDays, mechanic.constraint].join("|");
}
