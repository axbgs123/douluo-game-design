export function fixedTraitEffect(trait: string): string {
  if (/谨慎|审慎|戒备|多疑|警觉|细心|缜密|严谨/.test(trait)) return "调查、风险判断与准备更稳；建立信任更慢，突发行动更容易犹豫。";
  if (/勇敢|大胆|果断|好战|凶狠/.test(trait)) return "面对威胁和战斗时更敢行动；受挑衅时更难主动退让。";
  if (/好胜|野心|自负|控制欲|表演意识/.test(trait)) return "竞争、突破和争取地位的倾向更强；公开失败造成的心境压力更大。";
  if (/耐心|稳重|冷静|克制|从容|沉静/.test(trait)) return "修炼、研究和意志判定更稳定；情绪通常压住不说，关系升温较慢。";
  if (/重情|共情|仁心|知恩|护短|责任感|团队意识/.test(trait)) return "守诺、救援和关系维护更有优势；亲近之人受威胁时更容易承担额外风险。";
  if (/现实|务实|精明|圆滑|权衡|手段意识/.test(trait)) return "交易、资源和势力判断更敏锐；NPC可能觉得此人可靠，也可能觉得功利。";
  if (/好奇|好学|求真|巧思|专注|敏锐/.test(trait)) return "调查、学习和职业成长更快；面对未知线索时更难彻底放下。";
  if (/守秘|守口|秘密主义|谨言/.test(trait)) return "隐藏身份与秘密时更稳；坦白和求助更难，亲近者可能感到疏离。";
  if (/求道|执着|坚韧|耐劳|宿命感/.test(trait)) return "长期修炼与逆境意志更强；容易为认定的道路付出过高代价。";
  if (/叛逆|独立|自由/.test(trait)) return "拒绝命令和自定路线时意志更强；宗门、家族与导师更难约束。";
  return "作为身份形成的稳定倾向，会影响意志判定、NPC印象和后续性格修正。";
}
